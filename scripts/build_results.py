import json
from pathlib import Path

OUT = Path("results")

def load(name):
    p = OUT / name
    return json.loads(p.read_text()) if p.exists() else None

def pct(x):
    return f"{100*x:.2f}%"

def main():
    baseline = load("baseline_metrics.json")
    tensorflow = load("tensorflow_metrics.json")
    transformer = load("transformer_metrics.json")
    rows = []
    for name, obj in [
        ("TF-IDF + Logistic Regression", baseline),
        ("TensorFlow BiLSTM", tensorflow),
        ("DistilBERT (PyTorch)", transformer),
    ]:
        if obj:
            rows.append((
                name,
                obj["test"]["accuracy"],
                obj["test"]["macro_f1"],
                obj["test_routing"]["auto_coverage"],
                obj["test_routing"]["auto_accuracy"],
                obj["test_routing"]["review_rate"],
            ))
    md = [
        "# Verified Results",
        "",
        "Results below are generated by the full-data workflow on the official BANKING77 test set. Model/routing selection uses validation data only.",
        "",
        "| Model | Test accuracy | Macro-F1 | Auto-route coverage | Auto-route accuracy | Human review |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        md.append(f"| {r[0]} | {pct(r[1])} | {pct(r[2])} | {pct(r[3])} | {pct(r[4])} | {pct(r[5])} |")
    md += [
        "",
        "## Interpretation",
        "",
        "The project treats intent classification as an operational routing decision. The preferred model should balance class-level quality with automation coverage, confidence reliability, latency, and serving cost rather than being selected from accuracy alone.",
        "",
        "## Resume rule",
        "",
        "Use only numbers in this verified file after the full workflow succeeds.",
    ]
    Path("RESULTS.md").write_text("\n".join(md))

if __name__ == "__main__":
    main()
